CREATE TABLE IF NOT EXISTS ratan_flowzero_orchestration_service.t_retry_task (

    id                  VARCHAR(20)  NOT NULL,
    biz_type            VARCHAR(50)  NOT NULL,
    biz_id              VARCHAR(100) NOT NULL,
    payload             JSONB        NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    retry_count         INT          NOT NULL DEFAULT 0,
    max_retry           INT          NOT NULL DEFAULT 3,
    last_error          TEXT,
    next_retry_at       TIMESTAMP,
    synced_at           TIMESTAMP,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by          VARCHAR(100) NOT NULL,
    updated_by          VARCHAR(100) NOT NULL,
    version             INT          NOT NULL DEFAULT 0,

    CONSTRAINT pk_retry_task PRIMARY KEY (id),
    CONSTRAINT uq_retry_task_biz_type_id UNIQUE (biz_type, biz_id)
);

CREATE INDEX IF NOT EXISTS idx_rt_suspended_retry
    ON ratan_flowzero_orchestration_service.t_retry_task (biz_type, next_retry_at)
    WHERE status = 'SUSPENDED';

CREATE INDEX IF NOT EXISTS idx_rt_failed_retry
    ON ratan_flowzero_orchestration_service.t_retry_task (biz_type, next_retry_at, retry_count)
    WHERE status = 'FAILED';

CREATE INDEX IF NOT EXISTS idx_rt_biz_id_type
    ON ratan_flowzero_orchestration_service.t_retry_task (biz_id, biz_type);

CREATE INDEX IF NOT EXISTS idx_rt_biz_type_status_next_retry
    ON ratan_flowzero_orchestration_service.t_retry_task (biz_type, status, next_retry_at)
    WHERE status IN ('SUSPENDED', 'FAILED');

CREATE INDEX IF NOT EXISTS idx_rt_payload_gin
    ON ratan_flowzero_orchestration_service.t_retry_task USING GIN (payload);

