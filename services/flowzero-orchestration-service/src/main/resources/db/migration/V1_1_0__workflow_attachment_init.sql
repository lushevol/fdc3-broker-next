CREATE TABLE IF NOT EXISTS ratan_flowzero_orchestration_service.t_attachments (
    id                  VARCHAR(20)  NOT NULL,
    business_id         VARCHAR(100) NOT NULL,
    file_name           VARCHAR(500) NOT NULL,
    file_size           BIGINT,
    mime_type           VARCHAR(100),
    storage_type        VARCHAR(20)  NOT NULL,
    bucket              VARCHAR(500) NOT NULL DEFAULT '/',
    storage_ref         JSONB,
    status              VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    deleted_by          VARCHAR(100),
    deleted_at          TIMESTAMP,
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by          VARCHAR(100) NOT NULL,
    updated_by          VARCHAR(100) NOT NULL,
    version             INT          NOT NULL DEFAULT 0,

    CONSTRAINT pk_attachments PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_att_business_id_status
    ON ratan_flowzero_orchestration_service.t_attachments (business_id, status);

CREATE INDEX IF NOT EXISTS idx_att_status_created_at
    ON ratan_flowzero_orchestration_service.t_attachments (status, created_at)
    WHERE status = 'PENDING';


CREATE INDEX IF NOT EXISTS idx_att_storage_ref_gin
    ON ratan_flowzero_orchestration_service.t_attachments USING GIN (storage_ref)
    WHERE storage_ref IS NOT NULL;


